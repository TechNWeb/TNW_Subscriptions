namespace TNW\Subscriptions\Model\Config\Source;

/**
 * Class Enable Disable Options
 *
 */
class Enabledisable implements \Magento\Framework\Option\ArrayInterface
{
    /**
     * Options getter
     *
     * @return array
     */
    public function toOptionArray()
    {
        return [
            [
                'value' => 1,
                'label' => __('Enable')
            ],
            [
                'value' => 0,
                'label' => __('Disable')
            ]
        ];
    }

    /**
     * Get options in "key-value" format
     *
     * @return array
     */
    public function toArray()
    {
        return [
            0 => __('Disable'),
            1 => __('Enable')
        ];
    }
}